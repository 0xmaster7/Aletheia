def write_jsonl(path: Path, rows: list[dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("".join(json.dumps(row, ensure_ascii=False, separators=(",", ":")) + "\n" for row in rows), encoding="utf-8")


def load_secret() -> None:
    if os.environ.get("OPENAI_API_KEY"):
        return
    env_path = ROOT / ".env"
    if env_path.is_file():
        for line in env_path.read_text(encoding="utf-8").splitlines():
            if line.strip() and not line.lstrip().startswith("#") and "=" in line:
                key, _, value = line.partition("=")
                os.environ.setdefault(key.strip(), value.strip().strip("\"'"))
    if not os.environ.get("OPENAI_API_KEY"):
        raise RuntimeError("OPENAI_API_KEY unavailable; no request sent")


def verify_frozen() -> tuple[dict[str, Any], list[dict[str, Any]]]:
    frozen = json.loads(MANIFEST.read_text(encoding="utf-8"))
    hashes = frozen["prompt_and_code_hashes"]
    checks = {
        "final_v3_prompt_sha256": EXT / "config/frozen_setup/aletheia_final_v3_prompt.txt",
        "final_v3_operator_sha256": EXT / "config/frozen_setup/final_v3_operator.py",
        "base_operator_sha256": EXT / "config/frozen_setup/base_operator.py",
        "scorer_sha256": EXT / "config/frozen_setup/scorer.py",
        "react_system_prompt_sha256": REACT_PROMPT,
        "react_tool_schema_sha256": REACT_TOOL,
        "extension_config_sha256": CONFIG,
        "rrf_requests_sha256": RRFDIR / "requests.jsonl",
        "react_questions_sha256": REACTDIR / "questions.jsonl",
        "extension_runner_sha256": Path(__file__),
        "scoring_runner_sha256": EXT / "score_extensions.py",
    }
    for key, path in checks.items():
        if sha256_file(path) != hashes[key]:
            raise RuntimeError(f"Frozen input changed: {path}")
    rrf_requests = read_jsonl(RRFDIR / "requests.jsonl")
    if len(rrf_requests) != N:
        raise RuntimeError("Frozen RRF request count changed")
    return frozen, rrf_requests


def amount_from_usage(prompt_tokens: int, completion_tokens: int) -> float:
    return prompt_tokens * INPUT_RATE / 1_000_000 + completion_tokens * OUTPUT_RATE / 1_000_000


def ledger_spend(path: Path) -> float:
    if not path.exists():
        return 0.0
    return sum(float(r.get("actual_cost_usd") or 0) for r in read_jsonl(path))


def prior_extension_spend() -> float:
    return ledger_spend(RRFDIR / "calls.jsonl") + ledger_spend(REACTDIR / "calls.jsonl")


def can_start_call(spend_this_experiment: float, prior_spend: float, local_tokens: int, cap: int, experiment_limit: float) -> bool:
    guard = (local_tokens + 100) * INPUT_RATE / 1_000_000 + cap * OUTPUT_RATE / 1_000_000
    return spend_this_experiment + guard <= experiment_limit and prior_spend + spend_this_experiment + guard <= TOTAL_STOP


def client_or_raise():
    load_secret()
    from openai import OpenAI
    return OpenAI(max_retries=0, timeout=120)


def run_rrf() -> None:
    frozen, requests = verify_frozen()
    calls_path = RRFDIR / "calls.jsonl"
    if calls_path.exists():
        raise RuntimeError("RRF calls file exists; refusing any repeat")
    client = client_or_raise()
    spend = 0.0
    other_experiment_spend = ledger_spend(REACTDIR / "calls.jsonl")
    prompt_total = completion_total = 0
    for i, row in enumerate(requests, 1):
        if not can_start_call(spend, 0.0, int(row["local_input_tokens"]), 1024, RRF_STOP):
            write_json(RRFDIR / "checkpoint.json", {"status": "budget_guard_before_call", "completed_calls": i - 1,
                       "expected_calls": N, "experiment_spend_usd": spend, "global_spend_usd": other_experiment_spend + spend})
            break
        body = {key: row[key] for key in ("model", "messages", "temperature", "max_completion_tokens", "response_format")}
        started = time.time()
        try:
            response = client.chat.completions.create(**body)
        except Exception as exc:
            append_jsonl(calls_path, {"call_id": row["call_id"], "source_index": row["source_index"],
                          "intent": row["intent"], "status": "request_error", "error_type": type(exc).__name__,
                          "error": str(exc).replace(os.environ.get("OPENAI_API_KEY", ""), "[redacted]")[:1000],
                          "actual_cost_usd": None})
            write_json(RRFDIR / "checkpoint.json", {"status": "request_error_no_retry", "completed_calls": i - 1,
                       "expected_calls": N, "experiment_spend_usd": spend, "failed_call": row["call_id"]})
            break
        usage = response.usage
        if not usage or usage.prompt_tokens is None or usage.completion_tokens is None:
            append_jsonl(calls_path, {"call_id": row["call_id"], "source_index": row["source_index"],
                          "intent": row["intent"], "status": "usage_missing", "actual_cost_usd": None})
            write_json(RRFDIR / "checkpoint.json", {"status": "usage_missing_no_retry", "completed_calls": i,
                       "expected_calls": N, "experiment_spend_usd": spend, "failed_call": row["call_id"]})
            break
        cost = amount_from_usage(usage.prompt_tokens, usage.completion_tokens)
        spend += cost
        prompt_total += usage.prompt_tokens
        completion_total += usage.completion_tokens
        finish = response.choices[0].finish_reason
        record = {
            "call_id": row["call_id"], "source_index": row["source_index"], "question_id": row["question_id"],
            "intent": row["intent"], "flagged": row["source_gold_flagged"],
            "status": "truncated_failure" if finish == "length" else "completed",
            "usage_prompt_tokens": usage.prompt_tokens, "usage_completion_tokens": usage.completion_tokens,
            "finish_reason": finish, "request_id": getattr(response, "_request_id", None),
            "actual_cost_usd": round(cost, 10), "cumulative_experiment_spend_usd": round(spend, 10),
            "cumulative_total_spend_usd": round(other_experiment_spend + spend, 10),
            "elapsed_seconds": round(time.time() - started, 3),
            "request_messages": row["messages"], "response_format": row["response_format"],
            "response_text": response.choices[0].message.content or "",
        }
        append_jsonl(calls_path, record)
        write_json(RRFDIR / "checkpoint.json", {"status": "complete" if i == N else ("hard_stop_reached" if spend >= RRF_STOP else "running"),
                   "completed_calls": i, "expected_calls": N, "experiment_spend_usd": round(spend, 10),
                   "global_spend_usd": round(other_experiment_spend + spend, 10),
                   "prompt_tokens": prompt_total, "completion_tokens": completion_total,
                   "truncated_failures": sum(x.get("status") == "truncated_failure" for x in read_jsonl(calls_path)),
                   "last_call_id": row["call_id"]})
        if i % 10 == 0 or i == N:
            print(json.dumps({"experiment": "rrf_all300", "completed_calls": i, "expected": N,
                              "experiment_spend_usd": round(spend, 8), "prompt_tokens": prompt_total,
                              "completion_tokens": completion_total}), flush=True)
        if spend >= RRF_STOP or other_experiment_spend + spend >= TOTAL_STOP:
            break
    print(json.dumps({"experiment": "rrf_all300", "calls_logged": len(read_jsonl(calls_path)) if calls_path.exists() else 0,
                      "expected_calls": N, "spend_usd": round(spend, 8), "hard_stop_usd": RRF_STOP,
                      "total_spend_usd": round(other_experiment_spend + spend, 8)}, indent=2))


def local_message_tokens(messages: list[dict[str, Any]], tools: list[dict[str, Any]] | None) -> int:
    import tiktoken
    enc = tiktoken.get_encoding("o200k_base")
    count = 3
    for msg in messages:
        count += 4 + len(enc.encode(msg.get("role", "")))
        if isinstance(msg.get("content"), str):
            count += len(enc.encode(msg["content"]))
        elif msg.get("content") is not None:
            count += len(enc.encode(json.dumps(msg["content"], ensure_ascii=False, separators=(",", ":"))))
        if msg.get("tool_calls"):
            count += len(enc.encode(json.dumps(msg["tool_calls"], ensure_ascii=False, separators=(",", ":"))))
    if tools:
        count += len(enc.encode(json.dumps(tools, ensure_ascii=False, separators=(",", ":"))))
    return count


def search_memory(query: str, bm25: Any, facts: list[dict[str, Any]]) -> dict[str, Any]:
    import numpy as np
    scores = bm25.get_scores(RR.findall(query.lower()))
    positions = np.argsort(scores)[::-1][:10]
    return {"query": query, "results": [
        {"rank": rank, "fact_idx": facts[int(pos)]["fact_idx"], "text": facts[int(pos)]["text"],
         "bm25_score": float(scores[int(pos)])}
        for rank, pos in enumerate(positions, 1)
    ]}


def react_question(client: Any, row: dict[str, Any], bm25: Any, facts: list[dict[str, Any]],
                   exp_spend: float, global_before: float) -> tuple[dict[str, Any], float, int, int, bool]:
    tool = json.loads(REACT_TOOL.read_text(encoding="utf-8"))
    messages = [
        {"role": "system", "content": REACT_PROMPT.read_text(encoding="utf-8").strip()},
        {"role": "user", "content": row["question"]},
    ]
    search_count = 0
    records: list[dict[str, Any]] = []
    answer = None
    q_spend = 0.0
    q_prompt = q_completion = 0
    question_error = None
    react_config = json.loads(CONFIG.read_text(encoding="utf-8"))["experiment_2"]
    while True:
        final_only = search_count >= int(react_config["maximum_search_steps_per_question"])
        tools = [tool] if not final_only else [tool]
        tool_choice = "none" if final_only else "auto"
        local_tokens = local_message_tokens(messages, tools)
        if not can_start_call(exp_spend + q_spend, global_before, local_tokens, 512, REACT_STOP):
            question_error = "budget_guard_before_api_call"
            break
        started = time.time()
        try:
            response = client.chat.completions.create(
                model="gpt-4o-mini", messages=messages, temperature=0.0,
                max_completion_tokens=512, tools=tools, tool_choice=tool_choice,
                parallel_tool_calls=False,
            )
        except Exception as exc:
            record = {"source_index": row["source_index"], "question_id": row["question_id"],
                      "step": len(records) + 1, "status": "request_error", "error_type": type(exc).__name__,
                      "error": str(exc).replace(os.environ.get("OPENAI_API_KEY", ""), "[redacted]")[:1000],
                      "actual_cost_usd": None, "request_messages": messages, "tools": tools,
                      "tool_choice": tool_choice}
            append_jsonl(REACTDIR / "calls.jsonl", record)
            question_error = "request_error_no_retry"
            break
        usage = response.usage
        if not usage or usage.prompt_tokens is None or usage.completion_tokens is None:
            append_jsonl(REACTDIR / "calls.jsonl", {"source_index": row["source_index"], "question_id": row["question_id"],
                          "step": len(records) + 1, "status": "usage_missing", "actual_cost_usd": None,
                          "request_messages": messages, "tools": tools, "tool_choice": tool_choice})
            question_error = "usage_missing_no_retry"
            break
        cost = amount_from_usage(usage.prompt_tokens, usage.completion_tokens)
        q_spend += cost
        q_prompt += usage.prompt_tokens
        q_completion += usage.completion_tokens
        choice = response.choices[0]
        msg = choice.message.model_dump(mode="json", exclude_none=True)
        rec = {"source_index": row["source_index"], "question_id": row["question_id"],
               "step": len(records) + 1, "status": "truncated_failure" if choice.finish_reason == "length" else "completed",
               "usage_prompt_tokens": usage.prompt_tokens, "usage_completion_tokens": usage.completion_tokens,
               "finish_reason": choice.finish_reason, "request_id": getattr(response, "_request_id", None),
               "local_estimated_prompt_tokens": local_tokens, "actual_cost_usd": round(cost, 10),
               "elapsed_seconds": round(time.time() - started, 3), "request_messages": messages,
               "tools": tools, "tool_choice": tool_choice, "response_message": msg}
        records.append(rec)
        append_jsonl(REACTDIR / "calls.jsonl", rec)
        messages.append(msg)
        if choice.finish_reason == "length":
            question_error = "truncated_failure"
            break
        calls = msg.get("tool_calls") or []
        if not calls:
            answer = msg.get("content") or ""
            break
        if final_only or len(calls) != 1:
            question_error = "tool_protocol_error"
            break
        tool_call = calls[0]
        fn = tool_call.get("function", {})
        if fn.get("name") != "search_memory":
            question_error = "unknown_tool"
            break
        try:
            args = json.loads(fn.get("arguments", "{}"))
            query = args["query"]
            if not isinstance(query, str) or not query.strip():
                raise ValueError("search query must be nonempty text")
        except (ValueError, KeyError, TypeError, json.JSONDecodeError):
            question_error = "invalid_tool_arguments"
            break
        result = search_memory(query, bm25, facts)
        search_count += 1
        messages.append({"role": "tool", "tool_call_id": tool_call["id"],
                         "content": json.dumps(result, ensure_ascii=False, separators=(",", ":"))})
    output = {
        "source_index": row["source_index"], "question_id": row["question_id"], "question_number": row["question_number"],
        "intent": row["intent"], "question": row["question"], "gold": row["ground_truth_answer"],
        "flagged": row["source_gold_flagged"], "answer": answer, "answered": answer is not None and not question_error,
        "status": question_error or "completed", "search_steps": search_count, "model_api_calls": len(records),
        "prompt_tokens": q_prompt, "completion_tokens": q_completion,
        "actual_cost_usd": round(q_spend, 10), "transcript": messages,
        "per_call_usage": [{k: rec.get(k) for k in ("step", "usage_prompt_tokens", "usage_completion_tokens", "actual_cost_usd", "finish_reason", "request_id")} for rec in records],
    }
    return output, q_spend, q_prompt, q_completion, question_error is None


def run_react(pilot: bool) -> None:
    frozen, _ = verify_frozen()
    questions = read_jsonl(REACTDIR / "questions.jsonl")
    questions_path = REACTDIR / "question_runs.jsonl"
    call_path = REACTDIR / "calls.jsonl"
    existing = read_jsonl(questions_path) if questions_path.exists() else []
    prior_by_idx = {int(r["source_index"]): r for r in existing}
    if len(prior_by_idx) != len(existing):
        raise RuntimeError("Duplicate question-run records in ReAct output")
    if pilot:
        if existing or call_path.exists():
            raise RuntimeError("Pilot output already exists; refusing to repeat any call")
        targets = questions[:10]
    else:
        pilot_report_path = REACTDIR / "pilot_projection.json"
        if not pilot_report_path.exists():
            raise RuntimeError("ReAct pilot has not been run")
        pilot_report = json.loads(pilot_report_path.read_text(encoding="utf-8"))
        if pilot_report["projected_cost_usd_for_300"] > REACT_STOP:
            raise RuntimeError("Pilot projection exceeds $0.55; full run prohibited")
        if len(existing) != 10 or any(int(r["source_index"]) not in prior_by_idx for r in existing):
            raise RuntimeError("Expected exactly ten saved pilot question records before full run")
        if any(r["status"] not in {"completed", "truncated_failure", "tool_protocol_error", "unknown_tool", "invalid_tool_arguments"} for r in existing):
            raise RuntimeError("Pilot contains a request/usage error; full run prohibited")
        targets = questions[10:]
        if any(r["source_index"] in prior_by_idx for r in targets):
            raise RuntimeError("A full-run question already exists; refusing to repeat it")

    facts, context_sha, _ = load_corpus()
    if context_sha != frozen["factconsolidation_context_sha256"]:
        raise RuntimeError("ReAct corpus hash differs from frozen manifest")
    from rank_bm25 import BM25Okapi
    bm25 = BM25Okapi([RR.findall(f["text"].lower()) for f in facts])
    client = client_or_raise()
    exp_spend = ledger_spend(call_path)
    prior_spend = ledger_spend(RRFDIR / "calls.jsonl")
    prompt_total = completion_total = 0
    if call_path.exists():
        for rec in read_jsonl(call_path):
            prompt_total += int(rec.get("usage_prompt_tokens") or 0)
            completion_total += int(rec.get("usage_completion_tokens") or 0)
    stop_reason = None
    for row in targets:
        output, cost, p_tokens, c_tokens, ok = react_question(client, row, bm25, facts, exp_spend, prior_spend)
        append_jsonl(questions_path, output)
        exp_spend += cost
        prompt_total += p_tokens
        completion_total += c_tokens
        checkpoint = {"phase": "pilot" if pilot else "full", "questions_completed": len(read_jsonl(questions_path)),
                      "expected_total_questions": N, "experiment_2_spend_usd": round(exp_spend, 10),
                      "experiment_1_spend_usd": round(prior_spend, 10),
                      "cumulative_total_spend_usd": round(prior_spend + exp_spend, 10),
                      "prompt_tokens": prompt_total, "completion_tokens": completion_total,
                      "last_source_index": row["source_index"]}
        write_json(REACTDIR / "checkpoint.json", checkpoint)
        print(json.dumps({"question": row["question_number"], "source_index": row["source_index"],
                          "search_steps": output["search_steps"], "api_calls": output["model_api_calls"],
                          "spend_usd": output["actual_cost_usd"], "experiment_2_spend_usd": round(exp_spend, 8),
                          "status": output["status"]}), flush=True)
        if exp_spend >= REACT_STOP or prior_spend + exp_spend >= TOTAL_STOP:
            stop_reason = "hard_stop_reached"
            break
        if output["status"] in {"budget_guard_before_api_call", "request_error_no_retry", "usage_missing_no_retry"}:
            stop_reason = output["status"]
            break
    all_runs = read_jsonl(questions_path)
    if pilot:
        pilot_rows = [r for r in all_runs if int(r["question_number"]) <= 10]
        pilot_spends = [float(r["actual_cost_usd"]) for r in pilot_rows]
        avg = sum(pilot_spends) / len(pilot_spends) if len(pilot_spends) == 10 else None
        projection = avg * N if avg is not None else None
        report = {"pilot_questions_expected": 10, "pilot_questions_completed": len(pilot_rows),
                  "actual_cost_by_question_usd": [{"question_number": r["question_number"],
                    "source_index": r["source_index"], "actual_cost_usd": r["actual_cost_usd"],
                    "api_calls": r["model_api_calls"], "search_steps": r["search_steps"], "status": r["status"]} for r in pilot_rows],
                  "pilot_total_spend_usd": round(sum(pilot_spends), 10),
                  "mean_cost_per_question_usd": round(avg, 10) if avg is not None else None,
                  "projected_cost_usd_for_300": round(projection, 10) if projection is not None else None,
                  "full_run_authorized_by_cost_rule": bool(projection is not None and projection <= REACT_STOP),
                  "hard_stop_usd": REACT_STOP, "stop_reason": stop_reason}
        write_json(REACTDIR / "pilot_projection.json", report)
        print(json.dumps(report, indent=2))
    else:
        print(json.dumps({"phase": "full", "question_runs_saved": len(all_runs), "expected_questions": N,
                          "experiment_2_spend_usd": round(exp_spend, 8), "total_spend_usd": round(prior_spend + exp_spend, 8),
                          "prompt_tokens": prompt_total, "completion_tokens": completion_total,
                          "stop_reason": stop_reason or ("complete" if len(all_runs) == N else "incomplete")}, indent=2))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=("prepare", "run-rrf", "pilot-react", "run-react-full"))
    args = parser.parse_args()
    if args.action == "prepare":
        freeze()
    elif args.action == "run-rrf":
        run_rrf()
    elif args.action == "pilot-react":
        run_react(pilot=True)
    else:
        run_react(pilot=False)


if __name__ == "__main__":
    main()
