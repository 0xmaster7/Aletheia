def sha256_bytes(raw: bytes) -> str:
    return hashlib.sha256(raw).hexdigest()


def sha256_file(path: Path) -> str:
    return sha256_bytes(path.read_bytes())


def read_jsonl(path: Path) -> list[dict[str, Any]]:
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def write_json(path: Path, value: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def append_jsonl(path: Path, value: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", encoding="utf-8", buffering=1) as stream:
        stream.write(json.dumps(value, ensure_ascii=False, separators=(",", ":")) + "\n")
        stream.flush()
        os.fsync(stream.fileno())


def load_corpus() -> tuple[list[dict[str, Any]], str, str]:
    import pyarrow as pa
    import pyarrow.ipc as ipc
    from scripts.analysis.final_hybrid_confirmatory import parse_corpus_facts

    if not ARROW.is_file():
        raise FileNotFoundError(f"Pinned local Arrow cache missing: {ARROW}")
    with pa.memory_map(str(ARROW), "r") as source:
        dataset = ipc.open_stream(source).read_all().to_pylist()
    row = next((r for r in dataset if r["metadata"].get("source") == "factconsolidation_sh_262k"), None)
    if row is None:
        raise RuntimeError("Pinned FactConsolidation row is missing")
    context = row["context"]
    facts = parse_corpus_facts(context)
    return facts, sha256_bytes(context.encode("utf-8")), sha256_file(ARROW)


def stable_rank(scores: Any) -> list[int]:
    import numpy as np
    return np.argsort(-np.asarray(scores), kind="stable").tolist()


def compute_input_tokens(request: dict[str, Any]) -> int:
    import tiktoken
    enc = tiktoken.get_encoding("o200k_base")
    count = 3 + sum(4 + len(enc.encode(m["role"])) + len(enc.encode(m["content"]))
                    for m in request["messages"])
    if request.get("response_format"):
        raw = json.dumps(request["response_format"], ensure_ascii=False, separators=(",", ":"))
        count += len(enc.encode(raw))
    return count


